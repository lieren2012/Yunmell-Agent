"""Email verification codes and private deployment SMTP transport.

Codes are persisted in the control-plane database so they survive a restart
and work when more than one API worker handles a request. Only a SHA-256
digest is stored; the six-digit code is never returned by an API.
"""

from __future__ import annotations

import hashlib
import secrets
import smtplib
import time
from dataclasses import dataclass
from email.message import EmailMessage
from typing import Any

from octop.infra.users.email import normalize_email, validate_email_format

TTL_SECONDS = 600
COOLDOWN_SECONDS = 60
MAX_ATTEMPTS = 5


@dataclass(frozen=True)
class SmtpConfig:
    host: str
    port: int
    tls: bool
    sender: str
    username: str
    password: str
    enabled: bool

    @property
    def ready(self) -> bool:
        return bool(self.enabled and self.host and self.sender and self.username and self.password)


def _smtp_key(organization_id: str, field: str) -> str:
    return f"enterprise.smtp.{organization_id}.{field}"


def load_smtp_config(settings: Any, secrets_repo: Any, organization_id: str) -> SmtpConfig:
    """Read the enterprise SMTP config without exposing its password."""

    def prefix(field: str) -> str:
        return _smtp_key(organization_id, field)

    raw_password = secrets_repo.get(prefix("password"))
    password = raw_password.decode(errors="replace") if raw_password else ""
    raw_port = settings.get(prefix("port"))
    try:
        port = int(raw_port or 587)
    except (TypeError, ValueError):
        port = 587
    return SmtpConfig(
        host=str(settings.get(prefix("host")) or "").strip(),
        port=max(1, min(65535, port)),
        tls=(settings.get(prefix("tls")) or "true").lower() == "true",
        sender=str(settings.get(prefix("sender")) or "").strip(),
        username=str(settings.get(prefix("username")) or "").strip(),
        password=password,
        enabled=(settings.get(prefix("enabled")) or "false").lower() == "true",
    )


def send_message(config: SmtpConfig, recipient: str, subject: str, body: str) -> None:
    """Send one plain-text message over the configured SMTP connection."""
    if not config.ready:
        raise RuntimeError("SMTP is not configured or disabled")
    message = EmailMessage()
    message["From"] = config.sender
    message["To"] = recipient
    message["Subject"] = subject
    message.set_content(body)
    # ``tls`` means STARTTLS and matches the existing enterprise settings UI.
    with smtplib.SMTP(config.host, config.port, timeout=15) as smtp:
        smtp.ehlo()
        if config.tls:
            smtp.starttls()
            smtp.ehlo()
        smtp.login(config.username, config.password)
        smtp.send_message(message)


def _ensure_table(db: Any) -> None:
    """Create the tiny store for databases upgraded before migration 028."""
    ddl = """
        CREATE TABLE IF NOT EXISTS email_verification_codes (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          email TEXT NOT NULL,
          purpose TEXT NOT NULL,
          code_hash TEXT NOT NULL,
          created_at INTEGER NOT NULL,
          expires_at INTEGER NOT NULL,
          consumed_at INTEGER,
          attempts INTEGER NOT NULL DEFAULT 0
        );
        CREATE INDEX IF NOT EXISTS idx_email_verification_active
          ON email_verification_codes(email, purpose, expires_at, consumed_at);
    """
    pg_ddl = """
        CREATE TABLE IF NOT EXISTS email_verification_codes (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT NOT NULL,
          purpose TEXT NOT NULL,
          code_hash TEXT NOT NULL,
          created_at BIGINT NOT NULL,
          expires_at BIGINT NOT NULL,
          consumed_at BIGINT,
          attempts INTEGER NOT NULL DEFAULT 0
        );
        CREATE INDEX IF NOT EXISTS idx_email_verification_active
          ON email_verification_codes(email, purpose, expires_at, consumed_at);
    """
    with db.connect() as conn:
        if getattr(db, "dialect", "sqlite") == "postgresql":
            for statement in pg_ddl.split(";"):
                if statement.strip():
                    conn.execute(statement)
        else:
            conn.executescript(ddl)


def _digest(code: str) -> str:
    return hashlib.sha256(code.encode("ascii")).hexdigest()


def issue(db: Any, email: str, purpose: str) -> tuple[str, int]:
    """Create a six-digit code, returning ``(code, ttl_seconds)``."""
    normalized = normalize_email(email)
    if normalized is None:
        raise ValueError("email is required")
    validate_email_format(normalized)
    _ensure_table(db)
    now = int(time.time())
    with db.transaction() as conn:
        latest = conn.execute(
            "SELECT created_at FROM email_verification_codes "
            "WHERE email = ? AND purpose = ? AND consumed_at IS NULL "
            "ORDER BY id DESC LIMIT 1",
            (normalized, purpose),
        ).fetchone()
        if latest is not None and now - int(latest["created_at"]) < COOLDOWN_SECONDS:
            raise ValueError("verification code recently sent")
        code = f"{secrets.randbelow(1_000_000):06d}"
        conn.execute(
            "INSERT INTO email_verification_codes "
            "(email, purpose, code_hash, created_at, expires_at) VALUES (?, ?, ?, ?, ?)",
            (normalized, purpose, _digest(code), now, now + TTL_SECONDS),
        )
    return code, TTL_SECONDS


def verify(db: Any, email: str, purpose: str, code: str) -> bool:
    """Atomically consume a valid code, returning ``False`` on any mismatch."""
    normalized = normalize_email(email)
    candidate = str(code or "").strip()
    if normalized is None or not candidate:
        return False
    _ensure_table(db)
    now = int(time.time())
    with db.transaction() as conn:
        row = conn.execute(
            "SELECT id, code_hash, expires_at, attempts FROM email_verification_codes "
            "WHERE email = ? AND purpose = ? AND consumed_at IS NULL "
            "ORDER BY id DESC LIMIT 1",
            (normalized, purpose),
        ).fetchone()
        if row is None or int(row["expires_at"]) <= now:
            return False
        attempts = int(row["attempts"] or 0)
        if attempts >= MAX_ATTEMPTS:
            return False
        digest_matches = secrets.compare_digest(str(row["code_hash"]), _digest(candidate))
        if not digest_matches:
            conn.execute(
                "UPDATE email_verification_codes SET attempts = attempts + 1 WHERE id = ?",
                (int(row["id"]),),
            )
            return False
        conn.execute(
            "UPDATE email_verification_codes SET consumed_at = ? WHERE id = ?",
            (now, int(row["id"])),
        )
        return True


def clear(db: Any, email: str, purpose: str) -> None:
    """Remove outstanding codes for a user after a successful account flow."""
    normalized = normalize_email(email)
    if normalized is None:
        return
    _ensure_table(db)
    with db.transaction() as conn:
        conn.execute(
            "DELETE FROM email_verification_codes WHERE email = ? AND purpose = ?",
            (normalized, purpose),
        )
